export function animHTML(key){
  const a = ANIMS[key], M = PICT[key]; if (!a || !M) return "";
  return `<figure class="an">
    <div class="an-stage" data-pict="${key}"></div>
    <figcaption>
      <b>${M.title}</b>
      <ol>${a.steps.map(s => `<li>${s}</li>`).join("")}</ol>
      <p class="an-meta">${M.meta}</p>
      <p class="an-safe">${a.safety}</p>
    </figcaption>
  </figure>`;
}

// Один цикл на всю страницу: рисует все видимые сцены. Без движения в системе — кадр стоит на месте.
let started = false;
export function startPict(){
  if (started) return; started = true;
  if (!document.getElementById("pg-css")) { const st = document.createElement("style"); st.id = "pg-css"; st.textContent = PG_CSS; document.head.appendChild(st); }
  const still = matchMedia("(prefers-reduced-motion: reduce)").matches;
  const t0 = performance.now();
  (function frame(now){
    const t = still ? 1 : (now - t0) / 1000;
    for (const el of document.querySelectorAll("[data-pict]")) {
      const M = PICT[el.dataset.pict]; if (!M) continue;
      el.innerHTML = pictSvg(pictScene(M.pose(t), {guide:M, t}));
    }
    requestAnimationFrame(frame);
  })(t0);
}
